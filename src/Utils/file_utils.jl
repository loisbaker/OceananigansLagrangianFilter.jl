# Utilities for JLD2 and NetCDF files

"""
    copy_file_metadata!(original_file::JLD2.JLDFile, new_file::JLD2.JLDFile,
                        timeseries_vars_to_copy::Tuple{Vararg{String}})

Copies essential metadata from an existing Oceananigans JLD2 output file to a
new file.

This function is a utility for creating a new file structure with all
necessary simulation metadata (such as grid information and serialized
objects) without copying large timeseries data. It copies core simulation
metadata (`serialized`) and the `serialized` entries for
specified timeseries variables.

# Arguments
- `original_file::JLD2.JLDFile`: The source JLD2 file.
- `new_file::JLD2.JLDFile`: The destination JLD2 file.
- `timeseries_vars_to_copy::Tuple{Vararg{String}}`: A tuple of timeseries
  variable names e.g., ("u", "v").

"""
function copy_file_metadata!(original_file::JLD2.JLDFile, new_file::JLD2.JLDFile, 
                             timeseries_vars_to_copy::Tuple{Vararg{String}})

    # Copy over metadata that isn't associated with variables
    _copy_jld2_recursive!(original_file, new_file, "serialized")
    

    # Copy serialized entries for timeseries variables
    for var in timeseries_vars_to_copy
        _copy_jld2_recursive!(original_file, new_file, "timeseries/$var/serialized")
    end

end



"""
    _copy_jld2_recursive!(source::JLD2.JLDFile, dest::JLD2.JLDFile, path::String)

A helper function to recursively copy data and groups.
"""
function _copy_jld2_recursive!(source::JLD2.JLDFile, dest::JLD2.JLDFile, path::String)
    
    # Check if the path points to a JLD2 group
    if isa(source[path], JLD2.Group)
        # Recreate the group in the destination file
        dest_group = JLD2.Group(dest, path)

        # Recursively copy the contents of the group
        
        for key in keys(source[path])
            _copy_jld2_recursive!(source, dest, "$path/$key")
        end
    else
        # Simply copy the variable if it's not a group
        dest[path] = source[path]
    end
end

"""
    jld2_to_netcdf(jld2_filename::String, nc_filename::String)

Converts a JLD2 output file generated by an Oceananigans simulation into a
standard NetCDF file. This function is useful for post-processing and for
sharing data with other tools that expect the NetCDF format.

The conversion process involves the following steps:
1.  **Read JLD2 data**: Opens the input JLD2 file and reads the grid, time,
    and all timeseries variables.
2.  **Create NetCDF file**: Creates a new NetCDF file with a `.nc` extension.
3.  **Define dimensions**: Defines NetCDF dimensions based on the grid sizes
    and staggered locations (e.g., `x_caa` for cell centers, `x_faa` for
    cell faces). Only interior points are included, not halo cells.
4.  **Define grid variables**: Writes the grid coordinates, the cell spacings
    at each location (e.g., `dz_aaf`, or `dx_fca` on a `LatitudeLongitudeGrid`,
    where it varies with latitude) and metadata (e.g., `Lx`, `Ny`) as variables
    to the NetCDF file.
5.  **Write timeseries data**: Iterates through each variable in the JLD2
    file's timeseries, determines its location on the grid, and writes the
    interior of the data (dropping any halo cells) to a new variable in the
    NetCDF file.
6.  **Add metadata**: Adds attributes to each variable, including boundary
    conditions and units, for better documentation.

Arguments
=========
- `jld2_filename`: A `String` specifying the path to the input JLD2 file.
- `nc_filename`: A `String` specifying the path for the output NetCDF file.
"""
function jld2_to_netcdf(jld2_filename::String, nc_filename::String)
    jldopen(jld2_filename, "r") do file
        
        iterations = parse.(Int, keys(file["timeseries/t"]))
        times = [file["timeseries/t/$iter"] for iter in iterations]
        dt = times[2] - times[1]
        grid = file["serialized/grid"]

        rm(nc_filename, force=true)
        ds = NCDataset(nc_filename,"c", attrib = OrderedDict(
            "Julia"                     => "This file was generated using Julia Version $VERSION",

        ))

        # Coordinates of the interior nodes only: halo cells are not written to the NetCDF file.
        # A Flat direction has no nodes, so it gets a single dummy coordinate at zero.
        interior_coordinate(nodes) = isnothing(nodes) ? [0.0] : Array(nodes)

        if (grid isa RectilinearGrid) || ((grid isa ImmersedBoundaryGrid) && (grid.underlying_grid isa RectilinearGrid))
            coordinates = OrderedDict(
                "x_faa" => interior_coordinate(xnodes(grid, Face())),
                "x_caa" => interior_coordinate(xnodes(grid, Center())),
                "y_afa" => interior_coordinate(ynodes(grid, Face())),
                "y_aca" => interior_coordinate(ynodes(grid, Center())),
                "z_aaf" => interior_coordinate(znodes(grid, Face())),
                "z_aac" => interior_coordinate(znodes(grid, Center())),
            )
        # LatitudeLongitudeGrid has different names for the coordinate arrays
        elseif (grid isa LatitudeLongitudeGrid) || ((grid isa ImmersedBoundaryGrid) && (grid.underlying_grid isa LatitudeLongitudeGrid))
            coordinates = OrderedDict(
                "lon_faa" => interior_coordinate(λnodes(grid, Face())),
                "lon_caa" => interior_coordinate(λnodes(grid, Center())),
                "lat_afa" => interior_coordinate(φnodes(grid, Face())),
                "lat_aca" => interior_coordinate(φnodes(grid, Center())),
                "z_aaf"   => interior_coordinate(znodes(grid, Face())),
                "z_aac"   => interior_coordinate(znodes(grid, Center())),
            )
        else
            error("Grid type $(typeof(grid)) not supported for NetCDF conversion")
        end

        # Dimensions
        ds.dim["time"] = length(times)
        for (name, coordinate) in coordinates
            ds.dim[name] = length(coordinate)
        end
        
        # Declare and fill time variables

        nctime = defVar(ds,"time", Float64, ("time",), attrib = OrderedDict(
            "units"                     => "seconds",
            "long_name"                 => "Time",
        ))
        nctime[:] = times

        # There might be a time shifted variable
        if haskey(file["timeseries"], "t_shifted")
            t_shifted = [file["timeseries/t_shifted/$iter"] for iter in iterations]
            nctime = defVar(ds,"time_shifted", Float64, ("time",), attrib = OrderedDict(
            "units"                     => "seconds",
            "long_name"                 => "Time shifted to mean time",
            ))
            nctime[:] = t_shifted
        end

        # Declare and fill grid variables: the interior node coordinates...
        direction_names = Dict("x" => "x", "y" => "y", "z" => "z", "lon" => "longitude", "lat" => "latitude")
        coordinate_units = Dict("x" => "m", "y" => "m", "z" => "m", "lon" => "degrees_east", "lat" => "degrees_north")

        for (name, coordinate) in coordinates
            direction, location = split(name, "_")
            position = occursin('f', location) ? "face" : "center"
            ncvar = defVar(ds, name, Float32, (name,), attrib = OrderedDict(
                "units"                     => coordinate_units[direction],
                "long_name"                 => "Cell $position locations in the $(direction_names[direction]) direction.",
            ))
            ncvar[:] = coordinate
        end

        # ...and the cell spacings (in metres) at each location, taken from Oceananigans' spacing operators so that
        # stretched grids and grids without precomputed metrics are handled. On a LatitudeLongitudeGrid the x-spacing
        # varies with latitude (and with longitude if that is stretched), so x- and y-spacings are written in 2D.
        if (grid isa RectilinearGrid) || ((grid isa ImmersedBoundaryGrid) && (grid.underlying_grid isa RectilinearGrid))
            spacings = (
                ("dx_caa", ("x_caa",), xspacings(grid, Center())),
                ("dx_faa", ("x_faa",), xspacings(grid, Face())),
                ("dy_aca", ("y_aca",), yspacings(grid, Center())),
                ("dy_afa", ("y_afa",), yspacings(grid, Face())),
            )
        elseif (grid isa LatitudeLongitudeGrid) || ((grid isa ImmersedBoundaryGrid) && (grid.underlying_grid isa LatitudeLongitudeGrid))
            spacings = Tuple(("d$(d)_$(lx)$(ly)a", ("lon_$(lx)aa", "lat_a$(ly)a"), spacing(grid, ℓx, ℓy))
                             for (d, spacing) in (("x", xspacings), ("y", yspacings))
                             for (lx, ℓx) in (("c", Center()), ("f", Face()))
                             for (ly, ℓy) in (("c", Center()), ("f", Face())))
        else 
            error("Grid type $(typeof(grid)) not supported for NetCDF conversion")
        end
        spacings = (spacings..., ("dz_aac", ("z_aac",), zspacings(grid, Center())),
                                 ("dz_aaf", ("z_aaf",), zspacings(grid, Face())))

        for (name, dims, spacing) in spacings
            direction = name[2]
            ncvar = defVar(ds, name, Float32, dims, attrib = OrderedDict(
                "units"                     => "m",
                "long_name"                 => "Cell spacing in the $direction-direction, at cell $(name[4:end]) locations (c: center, f: face, a: any).",
            ))
            ncvar[:] = reshape(collect(spacing), Tuple(length(coordinates[dim]) for dim in dims))
        end

        # Define dimensions - the same for rectilinear and lat-lon grids
        ncNx = defVar(ds,"Nx", Int64, (), attrib = OrderedDict(
            "units"                     => "None",
            "long_name"                 => "Number of cells in the x-direction.",
        ))

        ncNx[:] = grid.Nx

        ncNy = defVar(ds,"Ny", Int64, (), attrib = OrderedDict(
            "units"                     => "None",
            "long_name"                 => "Number of cells in the y-direction.",
        ))
        ncNy[:] = grid.Ny


        ncNz = defVar(ds,"Nz", Int64, (), attrib = OrderedDict(
            "units"                     => "None",
            "long_name"                 => "Number of cells in the z-direction.",
        ))
        ncNz[:] = grid.Nz
        # Define dimension lengths

        ncLx = defVar(ds,"Lx", Float64, (), attrib = OrderedDict(
            "units"                     => "m",
            "long_name"                 => "Length of the domain in the x-direction.",
        ))
        ncLx[:] = grid.Lx
        ncLy = defVar(ds,"Ly", Float64, (), attrib = OrderedDict(
            "units"                     => "m",
            "long_name"                 => "Length of the domain in the y-direction.",
        ))
        ncLy[:] = grid.Ly   
        ncLz = defVar(ds,"Lz", Float64, (), attrib = OrderedDict(
            "units"                     => "m",
            "long_name"                 => "Length of the domain in the z-direction.",
        ))
        ncLz[:] = grid.Lz

        # And define location of variables
        if (grid isa RectilinearGrid) || ((grid isa ImmersedBoundaryGrid) && (grid.underlying_grid isa RectilinearGrid))
         
            location_map = Dict(
                (Center,Center,Center) => ("x_caa","y_aca","z_aac"),
                (Face,Center,Center)   => ("x_faa","y_aca","z_aac"),
                (Center,Face,Center)   => ("x_caa","y_afa","z_aac"),
                (Face,Face,Center)     => ("x_faa","y_afa","z_aac"),
                (Center,Center,Face)   => ("x_caa","y_aca","z_aaf"),
                (Face,Center,Face)     => ("x_faa","y_aca","z_aaf"),
                (Center,Face,Face)     => ("x_caa","y_afa","z_aaf"),
                (Face,Face,Face)       => ("x_faa","y_afa","z_aaf"),
            )
        elseif (grid isa LatitudeLongitudeGrid) || ((grid isa ImmersedBoundaryGrid) && (grid.underlying_grid isa LatitudeLongitudeGrid))
            location_map = Dict(
                (Center,Center,Center) => ("lon_caa","lat_aca","z_aac"),
                (Face,Center,Center)   => ("lon_faa","lat_aca","z_aac"),
                (Center,Face,Center)   => ("lon_caa","lat_afa","z_aac"),
                (Face,Face,Center)     => ("lon_faa","lat_afa","z_aac"),
                (Center,Center,Face)   => ("lon_caa","lat_aca","z_aaf"),
                (Face,Center,Face)     => ("lon_faa","lat_aca","z_aaf"),
                (Center,Face,Face)     => ("lon_caa","lat_afa","z_aaf"),
                (Face,Face,Face)       => ("lon_faa","lat_afa","z_aaf"),
            )
        else 
            error("Grid type $(typeof(grid)) not supported for NetCDF conversion")
        end

        for varname in keys(file["timeseries"])
            
            if varname ∉ ("t","t_shifted") 

                # Create a variable in the NetCDF file
                bc_string = sprint(show, file["timeseries/$varname/serialized/boundary_conditions"])
                dims = location_map[file["timeseries/$varname/serialized/location"]]
                ncv = defVar(ds, varname, Float64, (dims...,"time"), attrib = OrderedDict(
                    "boundary conditions"                     => bc_string,
                ))
                interior_size = Tuple(length(coordinates[dim]) for dim in dims)

                for (it,iter) in enumerate(iterations)
                    # Assign data to the variable, dropping any halo cells (an equal number either side)
                    data = file["timeseries/$varname/$iter"]
                    interior_indices = map((n, N) -> (n - N) ÷ 2 .+ (1:N), size(data), interior_size)
                    ncv[:, :, :, it] = data[interior_indices...]
                end
                
            end
        end

        close(ds)
        
    end
    @info "Wrote NetCDF file to $nc_filename"
end
